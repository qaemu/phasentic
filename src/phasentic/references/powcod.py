    def _reflection_count_array(self) -> np.ndarray:
        """Per-phase reflection counts (floored at 1), shape (phase_count,) float64.

        Reading the ``reflection_count`` column scans the whole phases table,
        which on a multi-gigabyte cache costs tens of seconds per process. The
        vector is therefore stored beside the cache, bound to the cache hash,
        exactly like the element-mask sidecar.
        """

        if self._reflection_counts is not None:
            return self._reflection_counts
        cache_sha = self._metadata().get("cache_sha256", "unknown")
        sidecar = self.cache_path.with_name(f"{self.cache_path.name}.refcounts1-{cache_sha[:16]}.npy")
        if sidecar.is_file():
            try:
                counts = np.load(sidecar, allow_pickle=False)
                if counts.shape == (self._phase_count,) and counts.dtype == np.float64:
                    self._reflection_counts = counts
                    return counts
            except (OSError, ValueError):
                pass
        counts = np.zeros(self._phase_count, dtype=np.float64)
        for phase_no, reflection_count in self._connection.execute(
            "SELECT phase_no, reflection_count FROM phases ORDER BY phase_no"
        ):
            index = int(phase_no)
            if 0 <= index < self._phase_count:
                counts[index] = max(float(reflection_count or 0.0), 1.0)
        self._reflection_counts = counts
        try:
            temporary = sidecar.with_suffix(".tmp.npy")
            np.save(temporary, counts, allow_pickle=False)
            os.replace(temporary, sidecar)
        except OSError:
            pass
        return counts

    def _element_mask_array(self) -> np.ndarray:
        """Per-phase element bit masks and an organic flag, shape (phase_count, 3) uint64.

        Built once from the cached formula column and stored beside the cache
        (bound to the cache hash) when the directory is writable. A formula that
        cannot be parsed gets all bits set, so it is excluded whenever an
        element filter is active.
        """

        if self._element_masks is not None:
            return self._element_masks
        cache_sha = self._metadata().get("cache_sha256", "unknown")
        sidecar = self.cache_path.with_name(f"{self.cache_path.name}.elements6-{cache_sha[:16]}.npy")
        if sidecar.is_file():
            try:
                masks = np.load(sidecar, allow_pickle=False)
                if masks.shape == (self._phase_count, 3) and masks.dtype == np.uint64:
                    self._element_masks = masks
                    return masks
            except (OSError, ValueError):
                pass
        masks = np.full((self._phase_count, 3), np.iinfo(np.uint64).max, dtype=np.uint64)
        for phase_no, formula in self._connection.execute("SELECT phase_no, formula FROM phases"):
            index = int(phase_no)
            if not 0 <= index < self._phase_count:
                continue
            parsed = parse_formula(str(formula or ""))
            if not parsed:
                continue
            low = high = 0
            for symbol in parsed:
                bit = ELEMENT_INDEX[symbol]
                if bit < 64:
                    low |= 1 << bit
                else:
                    high |= 1 << (bit - 64)
            masks[index, 0] = low
            masks[index, 1] = high
            carbon_allotrope = set(parsed) == {"C"} and parsed["C"] > 1.0 + 1e-9
            masks[index, 2] = 1 if is_molecular_organic(parsed) or carbon_allotrope else 0
        self._element_masks = masks
        try:
            temporary = sidecar.with_suffix(".tmp.npy")
            np.save(temporary, masks, allow_pickle=False)
            os.replace(temporary, sidecar)
        except OSError:
            pass
        return masks

    def element_eligibility(self, allowed_elements: Iterable[str] | None) -> np.ndarray | None:
        """Boolean array: phase contains only allowed elements (``None`` = no filter)."""

        if allowed_elements is None:
            return None
        low = high = 0
        for symbol in allowed_elements:
            bit = ELEMENT_INDEX[symbol]
            if bit < 64:
                low |= 1 << bit
            else:
                high |= 1 << (bit - 64)
        masks = self._element_mask_array()
        forbidden_low = np.uint64(~low & 0xFFFFFFFFFFFFFFFF)
        forbidden_high = np.uint64(~high & 0xFFFFFFFFFFFFFFFF)
        atmospheric = 0
        for symbol in ("H", "C", "N", "O"):
            atmospheric |= 1 << ELEMENT_INDEX[symbol]
        carbon_only = np.uint64(1 << ELEMENT_INDEX["C"])
        # Same rule as ``passes_element_filter``: at least one non-atmospheric
        # element (all non-atmospheric bits of ``low``/``high`` count), or
        # elemental carbon.
        not_atmospheric_low = np.uint64(~atmospheric & 0xFFFFFFFFFFFFFFFF)
        has_other = ((masks[:, 0] & not_atmospheric_low) != 0) | (masks[:, 1] != 0)
        is_carbon = (masks[:, 0] == carbon_only) & (masks[:, 1] == 0)
        return (
            ((masks[:, 0] & forbidden_low) == 0)
            & ((masks[:, 1] & forbidden_high) == 0)
            & (masks[:, 2] == 0)
            & (has_other | is_carbon)
        )

    def _phase_from_row(
        self,
        row: sqlite3.Row,
        radiation: Radiation,
        d_ranges: Iterable[tuple[float, float]] | None = None,
    ) -> ReferencePhase | None:
        cache_key = (int(row["phase_no"]), float(radiation.wavelength_angstrom))
        cached = self._decoded_phase_cache.get(cache_key)
        if cached is not None:
            self._decoded_phase_cache.move_to_end(cache_key)
            d_values, phase = cached
        else:
            d_values, phase = self._decode_phase(row, radiation)
            self._decoded_phase_cache[cache_key] = (d_values, phase)
            if len(self._decoded_phase_cache) > POWCOD_DECODED_PHASE_CACHE_SIZE:
                self._decoded_phase_cache.popitem(last=False)
        if d_ranges is not None:
            ranges = np.asarray(tuple(d_ranges), dtype=float).reshape(-1, 2)
            if ranges.size == 0 or not bool(
                np.any((d_values[:, None] >= ranges[None, :, 0]) & (d_values[:, None] <= ranges[None, :, 1]))
            ):
                return None
        return phase

    def _decode_phase(
        self,
        row: sqlite3.Row,
        radiation: Radiation,
    ) -> tuple[np.ndarray, ReferencePhase | None]:
        """Decode one cached row (pure for a fixed store and wavelength)."""

        d_values, intensities, hkl_values = _decode_reflection_arrays(row["reflection_blob"])
        # Vectorized Bragg filter to the 0-120 degree window.
        argument = radiation.wavelength_angstrom / (2.0 * np.maximum(d_values, 1e-12))
        valid = (d_values > 0) & (argument <= 1.0)
        angles = np.full(d_values.shape, np.inf)
        angles[valid] = np.degrees(2.0 * np.arcsin(argument[valid]))
        keep = np.flatnonzero((angles >= 0.0) & (angles <= 120.0))
        if keep.size == 0:
            return d_values, None
        if keep.size > POWCOD_MAX_LINES_PER_PHASE:
            # Very large cells list thousands of weak reflections; keep the
            # strongest ones (in database order) to bound decoding cost.
            strongest = np.argsort(-intensities[keep], kind="stable")[:POWCOD_MAX_LINES_PER_PHASE]
            keep = np.sort(keep[strongest])
        lines = [
            ReferenceLine(float(d_values[index]), float(intensities[index]), hkl_values[index] if hkl_values is not None else None)
            for index in keep
        ]
        equivalence = self._equivalence.lookup(str(row["reference_id"])) if self._equivalence else None
        return d_values, ReferencePhase(
            reference_id=str(row["reference_id"]),
            formula=str(row["formula"]),
            name=equivalence.preferred_name if equivalence else str(row["name"]),
            space_group=str(row["space_group"]),
            lines=tuple(lines),
            source="pow_cod",
            cod_entry_url=str(row["source_url"]),
            cod_entry_id=str(row["cod_id"]),
            equivalence_group_id=equivalence.group_id if equivalence else None,
            parent_family_group_id=equivalence.parent_family_group_id if equivalence else None,
            equivalence_kind=equivalence.equivalence_kind if equivalence else None,
            equivalence_confidence=equivalence.confidence if equivalence else None,
        )

    def _rows_by_reference_ids(self, reference_ids: Iterable[str]) -> tuple[sqlite3.Row, ...]:
        unique = tuple(sorted(set(reference_ids)))
        rows: list[sqlite3.Row] = []
        for offset in range(0, len(unique), 900):
            chunk = unique[offset : offset + 900]
            placeholders = ",".join("?" for _ in chunk)
            rows.extend(
                self._connection.execute(
                    f"SELECT * FROM phases WHERE reference_id IN ({placeholders}) ORDER BY phase_no", chunk
                ).fetchall()
            )
        return tuple(rows)

    def _rows_by_phase_numbers(self, phase_numbers: Iterable[int]) -> tuple[sqlite3.Row, ...]:
        unique = tuple(sorted({int(value) for value in phase_numbers if int(value) >= 0}))
        rows: list[sqlite3.Row] = []
        for offset in range(0, len(unique), 900):
            chunk = unique[offset : offset + 900]
            placeholders = ",".join("?" for _ in chunk)
            rows.extend(
                self._connection.execute(
                    f"SELECT * FROM phases WHERE phase_no IN ({placeholders}) ORDER BY phase_no", chunk
                ).fetchall()
            )
        return tuple(rows)

    def _phase_rows(
        self,
        reference_ids: Iterable[str],
        radiation: Radiation,
        d_ranges: Iterable[tuple[float, float]] | None = None,
    ) -> tuple[ReferencePhase, ...]:
        phases = [self._phase_from_row(row, radiation, d_ranges) for row in self._rows_by_reference_ids(reference_ids)]
        return tuple(phase for phase in phases if phase is not None)

    def get(self, reference_id: str, radiation: Radiation | str = "Cu Ka") -> ReferencePhase:
        normalized = reference_id if reference_id.startswith("powcod:") else f"powcod:{reference_id}"
        phases = self._phase_rows((normalized,), get_radiation(radiation))
        if not phases:
            raise KeyError(reference_id)
        return phases[0]

    def all(self, radiation: Radiation | str = "Cu Ka") -> tuple[ReferencePhase, ...]:
        ids = (str(row[0]) for row in self._connection.execute("SELECT reference_id FROM phases ORDER BY reference_id"))
        return self._phase_rows(ids, get_radiation(radiation))

    def _candidate_phase_bitsets(self, ranges: Iterable[tuple[float, float]]) -> tuple[int, ...]:
        """Return one packed phase bitset per observed d-spacing range.

        The previous implementation merged every matching bin into a Python
        ``bytearray`` and then materialized every phase number.  For a full
        POW_COD release, ordinary scans can match almost the entire universe;
        that made the later matcher decode hundreds of thousands of phase
        blobs before applying its small result limit.  Keeping each range as a
        Python integer lets the bitwise work run in C and enables a bounded,
        deterministic ranking before any reflection blobs are decoded.
        """

        bitsets: list[int] = []
        for lower, upper in ranges:
            first = max(0, int(math.floor(lower / self._d_bin_width)))
            last = max(first, int(math.floor(upper / self._d_bin_width)))
            bins: list[int] = []
            if first >= POWCOD_HIGH_D_BIN or last >= POWCOD_HIGH_D_BIN:
                bins.append(POWCOD_HIGH_D_BIN)
                last = POWCOD_HIGH_D_BIN - 1
            if first <= last:
                bins.extend(range(first, last + 1))
            if not bins:
                bitsets.append(0)
                continue
            mask = 0
            ordered_bins = tuple(sorted(set(bins)))
            for offset in range(0, len(ordered_bins), 900):
                chunk = ordered_bins[offset : offset + 900]
                placeholders = ",".join("?" for _ in chunk)
                for row in self._connection.execute(
                    f"SELECT phase_bits FROM d_bin_index WHERE bin IN ({placeholders})", chunk
                ):
                    mask |= int.from_bytes(bytes(row[0]), "little", signed=False)
            bitsets.append(mask)
        return tuple(bitsets)


    def _bounded_candidate_order(
        self,
        range_weights: tuple[float, ...],
        bitsets: tuple[int, ...],
        *,
        priority_budget: int,
        eligible: np.ndarray | None = None,
    ) -> tuple[int, ...]:
        """Return every coarse hit in the bounded policy's deterministic order.

        The first ``priority_budget`` values preserve the established
        compactness/major-support lanes. Remaining values are ordered by those
        same lanes and are available for exact-filter backfill.
        """

        merged = 0
        for bitset in bitsets:
            merged |= bitset
        candidate_count = merged.bit_count()
        if candidate_count == 0:
            return ()
        if candidate_count <= priority_budget:
            numbers = self._candidate_phase_numbers_from_bitset(merged)
            if eligible is not None:
                numbers = tuple(number for number in numbers if number < eligible.size and eligible[number])
            return numbers
        byte_count = max(1, (self._phase_count + 7) // 8)
        intensities = np.asarray(range_weights, dtype=np.float64)
        maximum = float(np.max(intensities)) if intensities.size else 0.0
        weights = intensities / maximum if maximum > 0.0 else np.ones(len(bitsets), dtype=np.float64)
        # Restrict the per-phase counting to eligible phases when an element
        # filter is active (a few hundred instead of ~490k).
        universe = np.flatnonzero(eligible) if eligible is not None else None
        size = universe.size if universe is not None else self._phase_count
        hit_count = np.zeros(size, dtype=np.uint16)
        weighted_hits = np.zeros(size, dtype=np.float64)
        for weight, bitset in zip(weights, bitsets, strict=True):
            bits = np.unpackbits(
                np.frombuffer(bitset.to_bytes(byte_count, "little", signed=False), dtype=np.uint8),
                bitorder="little",
            )[: self._phase_count]
            if universe is not None:
                bits = bits[universe]
            hit_count += bits
            weighted_hits += bits * float(weight)
        local = np.flatnonzero(hit_count)
        candidates = universe[local] if universe is not None else local
        candidate_hits = hit_count[local]
        candidate_weighted = weighted_hits[local]
        if candidates.size == 0:
            return ()
        # The bounded query reserves most of its budget for compact, coherent
        # line evidence while keeping a smaller major-peak-support lane. This
        # prevents a large, dense reference from winning only because it has
        # many opportunities for coarse-bin coincidence, without returning to
        # compactness-only lookup that can miss a phase explaining dominant
        # measured peaks. The count vector is loaded once per read-only store.
        compactness = candidate_hits / np.maximum(self._reflection_count_array()[candidates], 1.0)
        support_order = np.lexsort(
            (candidates, -compactness, -candidate_hits, -candidate_weighted)
        )
        compactness_order = np.lexsort(
            (candidates, -candidate_weighted, -candidate_hits, -compactness)
        )
        compactness_quota, major_support_quota = _bounded_retrieval_quotas(priority_budget)
        selected: list[int] = []
        selected_set: set[int] = set()
        for order, quota in (
            (compactness_order, compactness_quota),
            (support_order, major_support_quota),
        ):
            for candidate_index in order[:quota]:
                phase_number = int(candidates[candidate_index])
                if phase_number not in selected_set:
                    selected.append(phase_number)
                    selected_set.add(phase_number)
        # Remaining coarse hits (exact-filter backfill order): compactness order
        # first, then support order, skipping numbers already selected. This is
        # the same order as the previous per-element loop, computed in numpy.
        tail = np.concatenate([candidates[compactness_order], candidates[support_order]])
        if selected:
            tail = tail[~np.isin(tail, np.asarray(selected, dtype=tail.dtype))]
        _, first_positions = np.unique(tail, return_index=True)
        tail = tail[np.sort(first_positions)]
        return tuple(selected) + tuple(int(value) for value in tail)

    def _exact_candidate_backfill(
        self,
        phase_numbers: tuple[int, ...],
        radiation: Radiation,
        ranges: tuple[tuple[float, float], ...],
        *,
        limit: int,
    ) -> tuple[tuple[ReferencePhase, ...], dict[str, int | bool]]:
        """Verify coarse hits against exact d ranges before filling the pool.

        POW_COD's compact bitset bins are deliberately wider than a peak
        tolerance. A coarse false positive must not consume a fitter slot if a
        later-ranked candidate has an exact reflection in range. This scans
        deterministic batches and stops once the requested exact pool is full;
        the diagnostics distinguish a complete scan from an early bounded
        stop so callers can retain the remaining truncation uncertainty.
        """

        accepted: list[ReferencePhase] = []
        rejected = 0
        scanned = 0
        for offset in range(0, len(phase_numbers), 900):
            batch = phase_numbers[offset : offset + 900]
            rows = self._rows_by_phase_numbers(batch)
            by_number = {int(row["phase_no"]): row for row in rows}
            for phase_number in batch:
                row = by_number.get(phase_number)
                if row is None:
                    continue
                scanned += 1
                phase = self._phase_from_row(row, radiation, ranges)
                if phase is None:
                    rejected += 1
                    continue
                accepted.append(phase)
                if len(accepted) >= limit:
                    return tuple(accepted), {
                        "scanned_coarse_candidate_count": scanned,
                        "exact_prefilter_rejected_count": rejected,
                        "exact_candidates_found_in_scan": len(accepted),
                        "retrieval_complete": scanned == len(phase_numbers),
                        "backfilled_after_exact_filter": rejected > 0,
                    }
        return tuple(accepted), {
            "scanned_coarse_candidate_count": scanned,
            "exact_prefilter_rejected_count": rejected,
            "exact_candidates_found_in_scan": len(accepted),
            "retrieval_complete": True,
            "backfilled_after_exact_filter": rejected > 0,
        }

    def _exhaustive_exact_candidate_numbers(
        self,
        range_weights: tuple[float, ...],
        ranges: tuple[tuple[float, float], ...],
        max_candidates: int,
        eligible: np.ndarray | None = None,
    ) -> tuple[tuple[int, ...], int, int]:
        """Scan every cached phase and rank only exact line-position hits.

        This is deliberately an opt-in evaluation path.  It avoids the coarse
        d-bin false-negative risk by decoding each phase's compressed
        reflection evidence, then orders exact hits by measured-intensity
        support, hit count, and reference ID, matching the major-peak-first
        objective of bounded retrieval. The caller still receives a bounded
        pool, so reports must retain the exact candidate count and truncation
        flag when the pool is smaller than the match set.
        """

        ranked: list[tuple[int, int, float]] = []
        scanned = 0
        intensities = np.asarray(range_weights, dtype=np.float64)
        maximum = float(np.max(intensities)) if intensities.size else 0.0
        weights = intensities / maximum if maximum > 0.0 else np.ones(len(ranges), dtype=np.float64)
        for row in self._connection.execute(
            "SELECT phase_no, reflection_blob FROM phases ORDER BY phase_no"
        ):
            scanned += 1
            if eligible is not None and not eligible[int(row["phase_no"])]:
                continue
            d_spacings = _decode_d_spacings(row["reflection_blob"])
            hit_count = 0
            weighted_hits = 0.0
            for weight, (lower, upper) in zip(weights, ranges, strict=True):
                if bool(np.any((d_spacings >= lower) & (d_spacings <= upper))):
                    hit_count += 1
                    weighted_hits += float(weight)
            if hit_count:
                ranked.append((int(row["phase_no"]), hit_count, weighted_hits))
        ranked.sort(key=lambda value: (-value[2], -value[1], value[0]))
        return tuple(value[0] for value in ranked[:max_candidates]), len(ranked), scanned

    @staticmethod
    def _candidate_phase_numbers_from_bitset(bitset: int) -> tuple[int, ...]:
        numbers: list[int] = []
        remaining = bitset
        while remaining:
            lowest = remaining & -remaining
            numbers.append(lowest.bit_length() - 1)
            remaining ^= lowest
        return tuple(numbers)

    def iter_candidates(
        self,
        peaks: Iterable[Peak],
        radiation: Radiation | str,
        tolerance_deg: float,
        *,
        max_candidates: int | None = None,
        retrieval_mode: str = "bounded_coarse",
        allowed_elements: Iterable[str] | None = None,
        d_relative_tolerance: float = 0.0,
    ) -> tuple[ReferencePhase, ...]:
        selected = get_radiation(radiation)
        if not math.isfinite(d_relative_tolerance) or not 0.0 <= d_relative_tolerance <= 0.05:
            raise ValueError("d_relative_tolerance must be between 0 and 0.05")
        eligible = self.element_eligibility(tuple(allowed_elements) if allowed_elements is not None else None)
        if not math.isfinite(tolerance_deg) or tolerance_deg <= 0:
            raise ValueError("tolerance_deg must be positive and finite")
        if max_candidates is None:
            max_candidates = POWCOD_DEFAULT_CANDIDATE_LIMIT
        if isinstance(max_candidates, bool) or not isinstance(max_candidates, int) or max_candidates <= 0:
            raise ValueError("max_candidates must be a positive integer")
        if retrieval_mode not in POWCOD_RETRIEVAL_MODES:
            raise ValueError(f"retrieval_mode must be one of {POWCOD_RETRIEVAL_MODES}")
        observed_peaks = tuple(peaks)
        ranges: list[tuple[float, float]] = []
        range_weights: list[float] = []
        for peak in observed_peaks:
            lower = max(1e-9, float(peak.position_deg) - tolerance_deg)
            upper = min(179.999999, float(peak.position_deg) + tolerance_deg)
            if lower >= upper:
                continue
            try:
                values = (d_from_two_theta(lower, selected), d_from_two_theta(upper, selected))
            except ValueError:
                continue
            # Widen by the relative lattice tolerance so phases whose cell differs
            # slightly from the database entry are still retrieved.
            ranges.append((min(values) * (1.0 - d_relative_tolerance), max(values) * (1.0 + d_relative_tolerance)))
            range_weights.append(max(float(peak.intensity), 0.0))
        if not ranges:
            self._last_query_stats = {
                "candidate_limit": max_candidates,
                "candidate_count": 0,
                "returned_count": 0,
                "truncated": False,
                "retrieval_mode": retrieval_mode,
                "scanned_phase_count": 0,
                "selection": (
                    "exhaustive_exact_line_hits"
                    if retrieval_mode == "exhaustive_exact"
                    else "compactness_major_support_union_coarse_d_bin_hits"
                ),
                "retrieval_policy_version": POWCOD_RETRIEVAL_POLICY_VERSION,
                "compactness_quota": 0,
                "major_support_quota": 0,
            }
            return ()
        range_tuple = tuple(ranges)
        if retrieval_mode == "exhaustive_exact":
            phase_numbers, candidate_count, scanned_phase_count = self._exhaustive_exact_candidate_numbers(
                tuple(range_weights), range_tuple, max_candidates, eligible
            )
            selection = "exhaustive_exact_line_hits"
            phases = [
                self._phase_from_row(row, selected, ranges)
                for row in self._rows_by_phase_numbers(phase_numbers)
            ]
            result = tuple(phase for phase in phases if phase is not None)
            exact_stats: dict[str, int | bool] = {
                "coarse_candidate_count": candidate_count,
                "scanned_coarse_candidate_count": scanned_phase_count,
                "exact_prefilter_rejected_count": 0,
                "exact_candidates_found_in_scan": len(result),
                "retrieval_complete": True,
                "backfilled_after_exact_filter": False,
            }
        else:
            bitsets = self._candidate_phase_bitsets(range_tuple)
            merged = 0
            for bitset in bitsets:
                merged |= bitset
            candidate_count = merged.bit_count()
            phase_numbers = self._bounded_candidate_order(
                tuple(range_weights), bitsets, priority_budget=max_candidates, eligible=eligible
            )
            if eligible is not None:
                candidate_count = len(phase_numbers)
            selection = "compactness_major_support_union_coarse_d_bin_hits"
            result, exact_stats = self._exact_candidate_backfill(
                phase_numbers,
                selected,
                range_tuple,
                limit=max_candidates,
            )
            exact_stats = {"coarse_candidate_count": candidate_count, **exact_stats}
            scanned_phase_count = int(exact_stats["scanned_coarse_candidate_count"])
        compactness_quota, major_support_quota = (
            _bounded_retrieval_quotas(max_candidates)
            if retrieval_mode == "bounded_coarse" and candidate_count > max_candidates
            else (0, 0)
        )
        self._last_query_stats = {
            "candidate_limit": max_candidates,
            "candidate_count": candidate_count,
            "returned_count": len(result),
            "truncated": (
                candidate_count > max_candidates
                if retrieval_mode == "exhaustive_exact"
                else not bool(exact_stats["retrieval_complete"])
            ),
            "retrieval_mode": retrieval_mode,
            "scanned_phase_count": scanned_phase_count,
            "selection": selection,
            "retrieval_policy_version": POWCOD_RETRIEVAL_POLICY_VERSION,
            "compactness_quota": compactness_quota,
            "major_support_quota": major_support_quota,
            "element_filter": (
                {"allowed_elements": sorted(allowed_elements), "eligible_phase_count": int(eligible.sum())}
                if eligible is not None and allowed_elements is not None
                else None
            ),
            **exact_stats,
        }
        return result

    def __iter__(self) -> Iterable[ReferencePhase]:
        return iter(self.all())

    def close(self) -> None:
        connection = getattr(self, "_connection", None)
        if connection is not None:
            connection.close()
            self._connection = None
        if self._equivalence is not None:
            self._equivalence.close()
            self._equivalence = None

    def __enter__(self) -> "PowCodReferenceStore":
        return self

    def __exit__(self, *_: object) -> None:
        self.close()

    def __del__(self) -> None:
        try:
            self.close()
        except Exception:
            pass


