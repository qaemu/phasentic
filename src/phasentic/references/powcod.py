def verify_powcod_source(
    source_path: Path | str,
    *,
    info_path: Path | str | None = None,
) -> dict[str, object]:
    """Exhaustively validate a POW_COD source pair before runtime use.

    Preparation intentionally avoids repeating this multi-gigabyte scan. The
    explicit CLI verification command performs it once, records the source
    hashes, and leaves the read-only source databases untouched.
    """

    source = Path(source_path).expanduser().resolve()
    if not source.is_file():
        raise PowCodError(f"POWCOD_NOT_FOUND: {source}")
    info = _info_path(source, Path(info_path) if info_path is not None else None)
    if info is not None and not info.is_file():
        raise PowCodError(f"POWCOD_INFO_NOT_FOUND: {info}")
    table, _columns_map, info_table, _info_columns_map = _schema(source, info, check_integrity=True)
    with closing(_open_read_only(source, check_integrity=False)) as connection:
        source_rows = int(connection.execute(f"SELECT COUNT(*) FROM {_quote(table)}").fetchone()[0])
    info_rows = None
    if info is not None and info_table is not None:
        with closing(_open_read_only(info, check_integrity=False)) as connection:
            info_rows = int(connection.execute(f"SELECT COUNT(*) FROM {_quote(info_table)}").fetchone()[0])
    return {
        "source_path": str(source),
        "source_sha256": _sha256(source),
        "source_table": table,
        "source_rows": source_rows,
        "info_path": str(info) if info is not None else None,
        "info_sha256": _sha256(info) if info is not None else None,
        "info_table": info_table,
        "info_rows": info_rows,
        "status": "complete",
    }


class PowCodReferenceStore:
    """Read-only POW_COD sidecar-backed store with d-spacing candidate lookup."""

    def __init__(
        self,
        source_path: Path | str,
        *,
        cache_path: Path | str | None = None,
        info_path: Path | str | None = None,
        equivalence_path: Path | str | None = None,
    ) -> None:
        self.source_path = Path(source_path).expanduser().resolve()
        self.cache_path = Path(cache_path).expanduser().resolve() if cache_path is not None else self.source_path.with_name(self.source_path.name + ".xrd.sqlite")
        self.info_path = _info_path(self.source_path, Path(info_path) if info_path is not None else None)
        self.equivalence_path = Path(equivalence_path).expanduser().resolve() if equivalence_path is not None else None
        self._equivalence: EquivalenceSidecar | None = None
        if not self.source_path.is_file():
            raise PowCodError(f"POWCOD_NOT_FOUND: {self.source_path}")
        if not self.cache_path.is_file():
            raise PowCodError(f"POWCOD_CACHE_NOT_FOUND: run phasentic powcod prepare for {self.source_path.name}")
        # ``powcod verify`` is the explicit integrity gate.  Re-running a
        # multi-gigabyte SQLite integrity scan for every measured case would
        # make a 100-case campaign needlessly take hours before any matching
        # work begins.  Runtime still authenticates the immutable cache via
        # schema, build status, source stat identity, and the recorded cache
        # hash; operators can (and release checks do) run the exhaustive
        # verifier once before selecting the cache.
        self._connection = _open_read_only(self.cache_path, check_integrity=False)
        self._last_query_stats: dict[str, object] = {
            "candidate_limit": POWCOD_DEFAULT_CANDIDATE_LIMIT,
            "candidate_count": 0,
            "returned_count": 0,
            "truncated": False,
            "retrieval_mode": "bounded_coarse",
            "scanned_phase_count": 0,
            "selection": "compactness_major_support_union_coarse_d_bin_hits",
            "retrieval_policy_version": POWCOD_RETRIEVAL_POLICY_VERSION,
        }
        self._reflection_counts: np.ndarray | None = None
        # Decoded phases are pure functions of (phase_no, wavelength); residual
        # re-queries decode the same rows repeatedly, so keep a bounded LRU.
        self._decoded_phase_cache: OrderedDict[tuple[int, float], tuple[np.ndarray, ReferencePhase | None]] = OrderedDict()
        self._element_masks: np.ndarray | None = None
        try:
            metadata = self._metadata()
            if metadata.get("schema_version") != POWCOD_SCHEMA_VERSION:
                raise PowCodError("POWCOD_SCHEMA_UNSUPPORTED: cache schema version")
            if metadata.get("index_kind") != POWCOD_INDEX_KIND:
                raise PowCodError("POWCOD_SCHEMA_UNSUPPORTED: cache index kind")
            if metadata.get("reflection_encoding") != f"{_REFLECTION_MAGIC.decode('ascii')}-{_REFLECTION_ENCODING_VERSION}":
                raise PowCodError("POWCOD_SCHEMA_UNSUPPORTED: reflection encoding")
            if metadata.get("build_status") != "complete":
                raise PowCodError("POWCOD_CACHE_INCOMPLETE")
            try:
                self._phase_count = int(metadata["phase_count"])
                self._d_bin_width = float(metadata["d_bin_width_angstrom"])
                self._max_index_d = float(metadata["max_index_d_angstrom"])
            except (KeyError, TypeError, ValueError) as exc:
                raise PowCodError("POWCOD_SCHEMA_UNSUPPORTED: cache index metadata") from exc
            if (
                not math.isfinite(self._d_bin_width)
                or self._d_bin_width <= 0
                or not math.isfinite(self._max_index_d)
                or self._max_index_d <= 0
                or self._phase_count < 0
                or not math.isclose(self._d_bin_width, POWCOD_D_BIN_WIDTH_ANGSTROM, rel_tol=0.0, abs_tol=1e-12)
                or not math.isclose(self._max_index_d, POWCOD_MAX_INDEX_D_ANGSTROM, rel_tol=0.0, abs_tol=1e-9)
            ):
                raise PowCodError("POWCOD_SCHEMA_UNSUPPORTED: cache index metadata values")
            stat = self.source_path.stat()
            if str(stat.st_size) != metadata.get("source_size") or str(stat.st_mtime_ns) != metadata.get("source_mtime_ns"):
                raise PowCodError("POWCOD_SOURCE_CHANGED: rebuild the POW_COD cache")
            expected_info_size = metadata.get("info_size", "")
            expected_info_mtime = metadata.get("info_mtime_ns", "")
            if expected_info_size or expected_info_mtime:
                if self.info_path is None or not self.info_path.is_file():
                    raise PowCodError("POWCOD_INFO_CHANGED: rebuild the POW_COD cache")
                info_stat = self.info_path.stat()
                if str(info_stat.st_size) != expected_info_size or str(info_stat.st_mtime_ns) != expected_info_mtime:
                    raise PowCodError("POWCOD_INFO_CHANGED: rebuild the POW_COD cache")
            if self.equivalence_path is not None:
                try:
                    self._equivalence = EquivalenceSidecar.open(
                        self.equivalence_path,
                        expected_source_sha256=metadata.get("source_sha256"),
                        expected_cache_sha256=metadata.get("cache_sha256"),
                    )
                except EquivalenceError as exc:
                    raise PowCodError(f"POWCOD_EQUIVALENCE_INVALID: {exc}") from exc
        except Exception:
            self.close()
            raise

