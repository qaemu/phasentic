"""Read-only adapter and compact cache builder for the CNR POW_COD release.

POW_COD is distributed as one or two SQLite databases whose reflection arrays
are packed into text columns.  The source files are treated as immutable
external evidence.  This module creates a small normalized sidecar for fast
d-spacing queries and never writes to the supplied POW_COD database. The
sidecar keeps compressed per-phase reflection blobs and a d-spacing bitset
index rather than materializing one SQLite row for every reflection.
"""

