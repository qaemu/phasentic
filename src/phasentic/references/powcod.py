def _quote(identifier: str) -> str:
    return '"' + identifier.replace('"', '""') + '"'


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _open_read_only(path: Path, *, check_integrity: bool = True) -> sqlite3.Connection:
    resolved = Path(path).expanduser().resolve()
    if not resolved.is_file():
        raise PowCodError(f"POWCOD_NOT_FOUND: {resolved}")
    try:
        connection = sqlite3.connect(f"{resolved.as_uri()}?mode=ro", uri=True)
        connection.row_factory = sqlite3.Row
        connection.execute("PRAGMA query_only=ON")
        if check_integrity:
            integrity = connection.execute("PRAGMA integrity_check").fetchone()
            if integrity is None or str(integrity[0]).casefold() != "ok":
                connection.close()
                raise PowCodError(f"POWCOD_INTEGRITY_FAILED: {resolved}")
        return connection
    except sqlite3.Error as exc:
        raise PowCodError(f"POWCOD_UNREADABLE: {resolved}") from exc


def _tables(connection: sqlite3.Connection) -> tuple[str, ...]:
    rows = connection.execute(
        "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name"
    ).fetchall()
    return tuple(str(row[0]) for row in rows)


def _columns(connection: sqlite3.Connection, table: str) -> dict[str, str]:
    rows = connection.execute(f"PRAGMA table_info({_quote(table)})").fetchall()
    return {str(row[1]).casefold(): str(row[1]) for row in rows}


def _find_table(connection: sqlite3.Connection, preferred: str, required: set[str]) -> str:
    for table in _tables(connection):
        if table.casefold() == preferred.casefold():
            columns = _columns(connection, table)
            if required.issubset(columns):
                return table
    for table in _tables(connection):
        if required.issubset(_columns(connection, table)):
            return table
    raise PowCodError("POWCOD_SCHEMA_UNSUPPORTED: required POW_COD reflection columns are missing")


def _column(columns: Mapping[str, str], *names: str) -> str | None:
    for name in names:
        if name.casefold() in columns:
            return columns[name.casefold()]
    return None


def _info_path(source_path: Path, explicit: Path | None) -> Path | None:
    if explicit is not None:
        return explicit.expanduser().resolve()
    candidates = (
        source_path.with_name(source_path.name + ".info"),
        source_path.with_suffix(".info"),
    )
    return next((candidate for candidate in candidates if candidate.is_file()), None)


def _packed_values(value: Any) -> list[str]:
    if value is None:
        return []
    if isinstance(value, bytes):
        value = value.decode("utf-8", errors="replace")
    text = str(value).strip().strip("[]()")
    if not text:
        return []
    return [part.strip() for part in text.replace(";", ",").split(",") if part.strip()]


def _float_values(value: Any) -> list[float]:
    values: list[float] = []
    for part in _packed_values(value):
        try:
            parsed = float(part)
        except (TypeError, ValueError):
            continue
        if math.isfinite(parsed):
            values.append(parsed)
    return values



def _text(row: sqlite3.Row | None, columns: Mapping[str, str], *names: str) -> str | None:
    if row is None:
        return None
    selected = _column(columns, *names)
    if selected is None:
        return None
    value = row[selected]
    if value is None:
        return None
    text = str(value).strip()
    return text or None


def _schema(
    source_path: Path,
    info_path: Path | None,
    *,
    check_integrity: bool = True,
) -> tuple[str, dict[str, str], str | None, dict[str, str]]:
    with closing(_open_read_only(source_path, check_integrity=check_integrity)) as connection:
        # POW_COD 2205 stores packed d spacings and intensities in the main
        # database and keeps h/k/l, multiplicity, and cell metadata in the
        # companion ``.sq.info`` database. Older/synthetic fixtures may keep
        # h/k/l in the main table, so those columns remain optional below.
        table = _find_table(connection, "id", {"id", "dvalue", "intensita"})
        columns = _columns(connection, table)
    info_table: str | None = None
    info_columns: dict[str, str] = {}
    if info_path is not None and info_path.is_file():
        with closing(_open_read_only(info_path, check_integrity=check_integrity)) as connection:
            try:
                info_table = _find_table(connection, "info", {"id"})
                info_columns = _columns(connection, info_table)
            except PowCodError:
                info_table = None
    return table, columns, info_table, info_columns


def _fetch_info_rows(
    connection: sqlite3.Connection | None,
    table: str | None,
    columns: Mapping[str, str],
    id_column: str | None,
    ids: Iterable[str],
) -> dict[str, sqlite3.Row]:
    """Fetch only metadata for one bounded source batch.

    The native POW_COD 2205 ``.sq.info`` file is roughly two gigabytes. Loading
    every row at startup defeats the purpose of the compact sidecar and can
    exhaust a normal workstation. The table has an id index, so bounded IN
    queries preserve deterministic input order while keeping memory bounded.
    """

    if connection is None or table is None or id_column is None:
        return {}
    unique = tuple(sorted(set(ids)))
    if not unique:
        return {}
    selected = [id_column]
    for name in (
        "formula",
        "chemical_formula",
        "formula_sum",
        "name",
        "title",
        "compound_name",
        "mineralname",
        "source_url",
        "cod_url",
        "url",
        "spacegroup",
        "space_group",
        "a",
        "b",
        "c",
        "alpha",
        "beta",
        "gamma",
        "h",
        "k",
        "l",
    ):
        value = _column(columns, name)
        if value is not None and value not in selected:
            selected.append(value)
    result: dict[str, sqlite3.Row] = {}
    for offset in range(0, len(unique), 900):
        chunk = unique[offset : offset + 900]
        placeholders = ",".join("?" for _ in chunk)
        query = (
            f"SELECT {', '.join(_quote(value) for value in selected)} "
            f"FROM {_quote(table)} WHERE {_quote(id_column)} IN ({placeholders})"
        )
        for row in connection.execute(query, chunk):
            result[str(row[id_column]).strip()] = row
    return result


def _row_value(row: Mapping[str, Any] | sqlite3.Row | None, column: str | None) -> Any:
    if row is None or column is None:
        return None
    try:
        return row[column]
    except (IndexError, KeyError):
        return None


def _float_field(
    primary_row: Mapping[str, Any] | sqlite3.Row | None,
    primary_columns: Mapping[str, str],
    fallback_row: Mapping[str, Any] | sqlite3.Row | None,
    fallback_columns: Mapping[str, str],
    name: str,
) -> float | None:
    for row, columns in ((primary_row, primary_columns), (fallback_row, fallback_columns)):
        value = _row_value(row, _column(columns, name))
        if value is None:
            continue
        try:
            parsed = float(value)
        except (TypeError, ValueError):
            continue
        if math.isfinite(parsed):
            return parsed
    return None


def _encode_reflections(reflections: Iterable[tuple[float, float, str | None]]) -> bytes:
    """Encode one phase's reflection evidence compactly and deterministically.

    POW_COD stores packed arrays per phase. Expanding those arrays into one
    SQLite row per reflection multiplies the 458k-entry release into hundreds
    of millions of rows. This binary representation keeps the arrays packed,
    quantizes d spacings to the source's six-decimal precision, and compresses
    the result without discarding hkl evidence.
    """

    rows = tuple(reflections)
    payload = bytearray(struct.pack("<4sBI", _REFLECTION_MAGIC, _REFLECTION_ENCODING_VERSION, len(rows)))
    for d_spacing, _intensity, _hkl in rows:
        quantized = int(round(float(d_spacing) * 1_000_000.0))
        if not 0 < quantized <= 0xFFFFFFFF:
            raise PowCodError("POWCOD_REFLECTION_ENCODING: d spacing is outside the encodable range")
        payload.extend(struct.pack("<I", quantized))
    for _d_spacing, intensity, _hkl in rows:
        payload.extend(struct.pack("<f", float(intensity)))
    for _d_spacing, _intensity, hkl in rows:
        encoded = (hkl or "").encode("utf-8")
        if len(encoded) > 0xFFFF:
            raise PowCodError("POWCOD_REFLECTION_ENCODING: hkl evidence is too long")
        payload.extend(struct.pack("<H", len(encoded)))
        payload.extend(encoded)
    return zlib.compress(bytes(payload), level=9)


def _decode_reflections(blob: bytes) -> tuple[tuple[float, float, str | None], ...]:
    """Decode and validate a compact reflection blob from the sidecar."""

    try:
        payload = zlib.decompress(bytes(blob))
        magic, version, count = struct.unpack_from("<4sBI", payload, 0)
    except (TypeError, struct.error, zlib.error) as exc:
        raise PowCodError("POWCOD_CACHE_CORRUPT: reflection blob cannot be decoded") from exc
    if magic != _REFLECTION_MAGIC or version != _REFLECTION_ENCODING_VERSION:
        raise PowCodError("POWCOD_SCHEMA_UNSUPPORTED: reflection encoding version")
    offset = struct.calcsize("<4sBI")
    d_end = offset + 4 * count
    intensity_end = d_end + 4 * count
    if intensity_end > len(payload):
        raise PowCodError("POWCOD_CACHE_CORRUPT: reflection arrays are truncated")
    d_values = struct.unpack_from(f"<{count}I", payload, offset) if count else ()
    intensities = struct.unpack_from(f"<{count}f", payload, d_end) if count else ()
    offset = intensity_end
    hkl_values: list[str | None] = []
    for _ in range(count):
        if offset + 2 > len(payload):
            raise PowCodError("POWCOD_CACHE_CORRUPT: hkl evidence is truncated")
        size = struct.unpack_from("<H", payload, offset)[0]
        offset += 2
        if offset + size > len(payload):
            raise PowCodError("POWCOD_CACHE_CORRUPT: hkl evidence exceeds blob")
        text = payload[offset : offset + size].decode("utf-8") if size else ""
        offset += size
        hkl_values.append(text or None)
    return tuple((value / 1_000_000.0, float(intensity), hkl) for value, intensity, hkl in zip(d_values, intensities, hkl_values))


def _decode_reflection_arrays(blob: bytes) -> tuple[np.ndarray, np.ndarray, list[str | None] | None]:
    """Decode d-spacings and intensities as arrays; hkl text only for small blobs."""

    try:
        payload = zlib.decompress(bytes(blob))
        magic, version, count = struct.unpack_from("<4sBI", payload, 0)
    except (TypeError, struct.error, zlib.error) as exc:
        raise PowCodError("POWCOD_CACHE_CORRUPT: reflection blob cannot be decoded") from exc
    if magic != _REFLECTION_MAGIC or version != _REFLECTION_ENCODING_VERSION:
        raise PowCodError("POWCOD_SCHEMA_UNSUPPORTED: reflection encoding version")
    offset = struct.calcsize("<4sBI")
    d_end = offset + 4 * count
    intensity_end = d_end + 4 * count
    if intensity_end > len(payload):
        raise PowCodError("POWCOD_CACHE_CORRUPT: reflection arrays are truncated")
    d_values = np.frombuffer(payload, dtype="<u4", count=count, offset=offset).astype(np.float64) / 1_000_000.0
    intensities = np.frombuffer(payload, dtype="<f4", count=count, offset=d_end).astype(np.float64)
    hkl_values: list[str | None] | None = None
    if count <= POWCOD_MAX_LINES_PER_PHASE:
        hkl_values = [hkl for _d, _i, hkl in _decode_reflections(blob)]
    return d_values, intensities, hkl_values


def _decode_d_spacings(blob: bytes) -> np.ndarray:
    """Decode only d spacings for exhaustive position-recall scans.

    Exact candidate qualification does not need intensities or hkl strings.
    Avoiding those allocations keeps the full-library pass bounded in memory
    and substantially reduces Python work while preserving the same encoded
    source values used by ``_decode_reflections``.
    """

    try:
        payload = zlib.decompress(bytes(blob))
        magic, version, count = struct.unpack_from("<4sBI", payload, 0)
    except (TypeError, struct.error, zlib.error) as exc:
        raise PowCodError("POWCOD_CACHE_CORRUPT: reflection blob cannot be decoded") from exc
    if magic != _REFLECTION_MAGIC or version != _REFLECTION_ENCODING_VERSION:
        raise PowCodError("POWCOD_SCHEMA_UNSUPPORTED: reflection encoding version")
    offset = struct.calcsize("<4sBI")
    d_end = offset + 4 * count
    if d_end > len(payload):
        raise PowCodError("POWCOD_CACHE_CORRUPT: d-spacing array is truncated")
    encoded = np.frombuffer(payload, dtype="<u4", count=count, offset=offset)
    return encoded.astype(np.float64, copy=False) / 1_000_000.0


def _cache_hash(connection: sqlite3.Connection) -> str:
    digest = hashlib.sha256()
    for row in connection.execute(
        "SELECT phase_no, reference_id, cod_id, formula, name, space_group, source_url, "
        "a, b, c, alpha, beta, gamma, d_min, d_max, reflection_count, reflection_blob "
        "FROM phases ORDER BY phase_no"
    ):
        digest.update(json.dumps(tuple(row[:-1]), separators=(",", ":"), ensure_ascii=False).encode())
        digest.update(b"\n")
        digest.update(bytes(row[-1]))
        digest.update(b"\n")
    for row in connection.execute("SELECT bin, phase_bits FROM d_bin_index ORDER BY bin"):
        digest.update(struct.pack("<I", int(row[0])))
        digest.update(bytes(row[1]))
    return digest.hexdigest()


def _canonical_source_url(cod_id: str, supplied: str | None) -> str:
    return supplied or f"https://www.crystallography.net/cod/{cod_id}.html"


def build_powcod_cache(
    source_path: Path | str,
    cache_path: Path | str,
    *,
    info_path: Path | str | None = None,
    release: str = POWCOD_RELEASE,
) -> PowCodCacheResult:
    """Normalize a POW_COD release into a deterministic query sidecar."""

    source = Path(source_path).expanduser().resolve()
    if not source.is_file():
        raise PowCodError(f"POWCOD_NOT_FOUND: {source}")
    info = _info_path(source, Path(info_path) if info_path is not None else None)
    if info is not None and not info.is_file():
        raise PowCodError(f"POWCOD_INFO_NOT_FOUND: {info}")
    # Preparation reads both databases read-only and defers the full SQLite
    # integrity scan to ``powcod verify``. This keeps a multi-gigabyte build
    # from scanning every page twice while still providing an explicit
    # exhaustive verification command before runtime selection.
    table, columns, info_table, info_columns = _schema(source, info, check_integrity=False)
    id_column = _column(columns, "id")
    h_column = _column(columns, "h")
    k_column = _column(columns, "k")
    l_column = _column(columns, "l")
    d_column = _column(columns, "dvalue")
    intensity_column = _column(columns, "intensita")
    assert id_column and d_column and intensity_column
    space_group_column = _column(columns, "spacegroup", "spacegroup_x", "space_group")
    cell_columns = {name: _column(columns, name) for name in ("a", "b", "c", "alpha", "beta", "gamma")}
    source_formula_column = _column(columns, "formula", "chemical_formula", "formula_sum")
    source_name_column = _column(columns, "name", "title", "compound_name", "mineralname")
    source_url_column = _column(columns, "source_url", "cod_url", "url")
    info_id_column = _column(info_columns, "id") if info_table is not None else None
    info_h_column = _column(info_columns, "h")
    info_k_column = _column(info_columns, "k")
    info_l_column = _column(info_columns, "l")
    source_sha = _sha256(source)
    info_sha = _sha256(info) if info is not None else None
    output = Path(cache_path).expanduser().resolve()
    output.parent.mkdir(parents=True, exist_ok=True)
    temporary = output.with_name(f".{output.name}.building")
    temporary.unlink(missing_ok=True)
    source_stat = source.stat()
    info_stat = info.stat() if info is not None else None
    try:
        with closing(_open_read_only(source, check_integrity=False)) as source_connection:
            info_connection = (
                _open_read_only(info, check_integrity=False)
                if info is not None and info_table is not None
                else None
            )
            try:
                with closing(sqlite3.connect(temporary)) as cache:
                    cache.executescript(
                    """
                    PRAGMA journal_mode=DELETE;
                    CREATE TABLE metadata (key TEXT PRIMARY KEY, value TEXT NOT NULL);
                    CREATE TABLE phases (
                        phase_no INTEGER PRIMARY KEY,
                        reference_id TEXT NOT NULL UNIQUE,
                        cod_id TEXT NOT NULL,
                        formula TEXT NOT NULL,
                        name TEXT NOT NULL,
                        space_group TEXT NOT NULL,
                        source_url TEXT NOT NULL,
                        a REAL, b REAL, c REAL, alpha REAL, beta REAL, gamma REAL,
                        d_min REAL,
                        d_max REAL,
                        reflection_count INTEGER NOT NULL,
                        reflection_blob BLOB NOT NULL
                    );
                    CREATE UNIQUE INDEX phases_reference_idx ON phases(reference_id);
                    CREATE TABLE d_bin_index (
                        bin INTEGER PRIMARY KEY,
                        phase_bits BLOB NOT NULL
                    );
                    CREATE TABLE quality_flags (
                        reference_id TEXT NOT NULL,
                        code TEXT NOT NULL,
                        message TEXT NOT NULL
                    );
                    """
                    )
                    metadata = {
                    "schema_version": POWCOD_SCHEMA_VERSION,
                    "adapter_version": POWCOD_ADAPTER_VERSION,
                    "index_kind": POWCOD_INDEX_KIND,
                    "d_bin_width_angstrom": str(POWCOD_D_BIN_WIDTH_ANGSTROM),
                    "max_index_d_angstrom": str(POWCOD_MAX_INDEX_D_ANGSTROM),
                    "reflection_encoding": f"{_REFLECTION_MAGIC.decode('ascii')}-{_REFLECTION_ENCODING_VERSION}",
                    "release": str(release),
                    "source_path_name": source.name,
                    "source_sha256": source_sha,
                    "source_size": str(source_stat.st_size),
                    "source_mtime_ns": str(source_stat.st_mtime_ns),
                    "info_path_name": info.name if info is not None else "",
                    "info_sha256": info_sha or "",
                    "info_size": str(info_stat.st_size) if info_stat is not None else "",
                    "info_mtime_ns": str(info_stat.st_mtime_ns) if info_stat is not None else "",
                    "source_url": POWCOD_SOURCE_URL,
                    "license": POWCOD_LICENSE,
                    "attribution": POWCOD_ATTRIBUTION,
                    "intensity_model": "POW_COD calculated relative intensities; native configuration must be verified per release",
                    "build_status": "building",
                }
                    cache.executemany("INSERT INTO metadata(key, value) VALUES (?, ?)", metadata.items())
                    phase_count = 0
                    line_count = 0
                    estimated_phase_rows = int(source_connection.execute(f"SELECT COUNT(*) FROM {_quote(table)}").fetchone()[0])
                    bitset_length = max(1, (estimated_phase_rows + 7) // 8)
                    d_bin_bits: dict[int, bytearray] = {}
                    phase_rows: list[tuple[Any, ...]] = []
                    flag_rows: list[tuple[Any, ...]] = []
                    select_columns: list[str] = [id_column]
                    for candidate in (
                        space_group_column,
                        source_formula_column,
                        source_name_column,
                        source_url_column,
                        *cell_columns.values(),
                        h_column,
                        k_column,
                        l_column,
                        d_column,
                        intensity_column,
                    ):
                        if candidate and candidate not in select_columns:
                            select_columns.append(candidate)
                    source_columns = {key.casefold(): key for key in select_columns}
                    source_cursor = source_connection.execute(
                        f"SELECT {', '.join(_quote(value) for value in select_columns)} "
                        f"FROM {_quote(table)} ORDER BY {_quote(id_column)}"
                    )
                    while True:
                        source_batch = source_cursor.fetchmany(1000)
                        if not source_batch:
                            break
                        source_ids = (str(row[id_column]).strip() for row in source_batch if row[id_column] is not None)
                        info_rows = _fetch_info_rows(
                            info_connection,
                            info_table,
                            info_columns,
                            info_id_column,
                            source_ids,
                        )
                        for row in source_batch:
                            raw_id = row[id_column]
                            cod_id = str(raw_id).strip() if raw_id is not None else ""
                            if not cod_id:
                                continue
                            info_row = info_rows.get(cod_id)
                            formula = (
                                _text(row, source_columns, "formula", "chemical_formula", "formula_sum")
                                or _text(info_row, info_columns, "formula", "chemical_formula", "formula_sum")
                                or "Unknown"
                            )
                            name = (
                                _text(row, source_columns, "name", "title", "compound_name", "mineralname")
                                or _text(info_row, info_columns, "name", "title", "compound_name", "mineralname")
                                or f"COD {cod_id}"
                            )
                            supplied_url = (
                                _text(row, source_columns, "source_url", "cod_url", "url")
                                or _text(info_row, info_columns, "source_url", "cod_url", "url")
                            )
                            space_group = (
                                _text(row, source_columns, "spacegroup", "spacegroup_x", "space_group")
                                or _text(info_row, info_columns, "spacegroup", "space_group")
                                or "Unknown"
                            )
                            reference_id = f"powcod:{cod_id}"
                            d_values = _float_values(_row_value(row, d_column))
                            intensities = _float_values(_row_value(row, intensity_column))
                            h_values = _packed_values(_row_value(row, h_column)) or _packed_values(_row_value(info_row, info_h_column))
                            k_values = _packed_values(_row_value(row, k_column)) or _packed_values(_row_value(info_row, info_k_column))
                            l_values = _packed_values(_row_value(row, l_column)) or _packed_values(_row_value(info_row, info_l_column))
                            usable = min(len(d_values), len(intensities))
                            reflections: list[tuple[float, float, str | None]] = []
                            for index in range(usable):
                                d_value = d_values[index]
                                intensity = intensities[index]
                                if not math.isfinite(d_value) or d_value <= 0 or not math.isfinite(intensity) or intensity < 0:
                                    continue
                                hkl = None
                                if index < len(h_values) and index < len(k_values) and index < len(l_values):
                                    components = (h_values[index], k_values[index], l_values[index])
                                    hkl = (
                                        "".join(components)
                                        if all(len(component) == 1 and component.isdigit() for component in components)
                                        else " ".join(components)
                                    )
                                reflections.append((d_value, intensity, hkl))
                            phase_no = phase_count
                            phase_count += 1
                            d_min = min((reflection[0] for reflection in reflections), default=None)
                            d_max = max((reflection[0] for reflection in reflections), default=None)
                            phase_rows.append(
                                (
                                    phase_no,
                                    reference_id,
                                    cod_id,
                                    formula,
                                    name,
                                    space_group,
                                    _canonical_source_url(cod_id, supplied_url),
                                    *(
                                        _float_field(row, source_columns, info_row, info_columns, field)
                                        for field in cell_columns
                                    ),
                                    d_min,
                                    d_max,
                                    len(reflections),
                                    _encode_reflections(reflections),
                                )
                            )
                            line_count += len(reflections)
                            for d_value, _intensity, _hkl in reflections:
                                bin_number = min(
                                    int(math.floor(d_value / POWCOD_D_BIN_WIDTH_ANGSTROM)),
                                    POWCOD_HIGH_D_BIN,
                                )
                                bits = d_bin_bits.setdefault(bin_number, bytearray(bitset_length))
                                bits[phase_no // 8] |= 1 << (phase_no % 8)
                            if not reflections:
                                flag_rows.append((reference_id, "no_valid_reflections", "No usable d-spacing/intensity pair was present in POW_COD row"))
                            if len(phase_rows) >= 1000:
                                cache.executemany("INSERT INTO phases VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)", phase_rows)
                                cache.executemany("INSERT INTO quality_flags VALUES (?, ?, ?)", flag_rows)
                                phase_rows.clear()
                                flag_rows.clear()
                    if phase_rows:
                        cache.executemany("INSERT INTO phases VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)", phase_rows)
                        cache.executemany("INSERT INTO quality_flags VALUES (?, ?, ?)", flag_rows)
                    actual_bitset_length = max(1, (phase_count + 7) // 8)
                    cache.executemany(
                        "INSERT INTO d_bin_index(bin, phase_bits) VALUES (?, ?)",
                        ((bin_number, bytes(bits[:actual_bitset_length])) for bin_number, bits in sorted(d_bin_bits.items())),
                    )
                    cache_hash = _cache_hash(cache)
                    cache.executemany(
                        "INSERT INTO metadata(key, value) VALUES (?, ?) ON CONFLICT(key) DO UPDATE SET value=excluded.value",
                        (("phase_count", str(phase_count)), ("line_count", str(line_count)), ("cache_sha256", cache_hash), ("build_status", "complete")),
                    )
                    cache.commit()
            finally:
                if info_connection is not None:
                    info_connection.close()
        os.replace(temporary, output)
    except Exception:
        temporary.unlink(missing_ok=True)
        raise
    return PowCodCacheResult(source, output, info, str(release), source_sha, info_sha, cache_hash, phase_count, line_count)


